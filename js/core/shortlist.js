/**
 * Shortlist — local only.
 *
 * The shortlist never leaves the browser: it lives in localStorage and can be
 * exported as Markdown from the shortlist page.
 */

const KEY = 'contribmatch:v1:shortlist';

/**
 * @param {{storage?: Storage}} [deps]
 */
export function createShortlist({ storage } = {}) {
  const store =
    storage ??
    (() => {
      try {
        return globalThis.localStorage;
      } catch {
        return null;
      }
    })();

  function read() {
    try {
      const raw = store?.getItem(KEY);
      if (!raw) return [];
      const parsed = JSON.parse(raw);
      return Array.isArray(parsed) ? parsed : [];
    } catch {
      return [];
    }
  }

  function write(items) {
    try {
      store?.setItem(KEY, JSON.stringify(items));
    } catch {
      /* ignore */
    }
  }

  return {
    list() {
      return read();
    },

    has(id) {
      return read().some((item) => String(item.id) === String(id));
    },

    /**
     * @param {object} issue a normalised issue
     */
    add(issue) {
      const items = read();
      const id = String(issue.id);
      if (items.some((item) => String(item.id) === id)) return items;
      const entry = {
        id: issue.id,
        number: issue.number,
        title: issue.title,
        repo: issue.repo,
        owner: issue.owner,
        language: issue.language,
        labels: issue.labels || [],
        url: issue.htmlUrl,
        score: typeof issue.score === 'number' ? issue.score : null,
        addedAt: new Date().toISOString(),
      };
      items.push(entry);
      write(items);
      return items;
    },

    remove(id) {
      const items = read().filter((item) => String(item.id) !== String(id));
      write(items);
      return items;
    },

    toggle(issue) {
      if (this.has(issue.id)) {
        this.remove(issue.id);
        return { added: false, items: this.list() };
      }
      return { added: true, items: this.add(issue) };
    },

    clear() {
      write([]);
    },

    /** Export the shortlist as a Markdown checklist. */
    toMarkdown() {
      const items = read();
      const lines = ['# ContribMatch shortlist', ''];
      if (!items.length) {
        lines.push('_No issues saved yet._', '');
        return lines.join('\n');
      }
      for (const item of items) {
        const repo = item.repo || 'unknown repository';
        const labels = (item.labels || []).map((l) => `\`${l}\``).join(', ');
        lines.push(`- [ ] [${item.title}](${item.url}) — ${repo}${labels ? ` (${labels})` : ''}`);
      }
      lines.push('', `_${items.length} issue${items.length === 1 ? '' : 's'} — generated by ContribMatch._`);
      return lines.join('\n');
    },
  };
}
